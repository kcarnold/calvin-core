/**
 * One-shot script: parse catalog-<catoid>.html → catalog-categories-<catoid>.json
 *
 * Extracts the pure-data fields from parseCoreProgram() output, stripping
 * all DOM element references. The resulting JSON is hand-verifiable,
 * diffable, and loads instantly (no JSDOM needed for logic tests).
 *
 * Usage:
 *   node test/generate-catalog-json.js [catoid]   (default: 25)
 *
 * catalog-<catoid>.html must be saved from a browser: catalog.calvin.edu sits
 * behind a bot challenge, so plain fetch/curl gets an empty page.
 * Re-run when the catalog changes (typically once per academic year).
 *
 * Also regenerates src/catalog-courses.js: the union of every
 * catalog-categories-*.json, so a course listed for a requirement in any known
 * catalog counts toward it regardless of which catalog page is open.
 */

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { JSDOM } from 'jsdom';
import { parseCoreProgram } from '../src/core.js';

const __dirname = fileURLToPath(new URL('.', import.meta.url));
const CATOID = process.argv[2] || '25';
const CATALOG_YEARS = { '24': '2025-26', '25': '2026-27' };
const FIXTURES = join(__dirname, 'fixtures');
const UNION_OUTPUT = join(__dirname, '..', 'src', 'catalog-courses.js');
const CATALOG_HTML = join(__dirname, 'fixtures', `catalog-${CATOID}.html`);
const OUTPUT = join(__dirname, 'fixtures', `catalog-categories-${CATOID}.json`);

if (!existsSync(CATALOG_HTML)) {
  console.error(`Missing ${CATALOG_HTML}. Save the core program page's HTML from a browser.`);
  process.exit(1);
}

const html = readFileSync(CATALOG_HTML, 'utf-8');
const doc = new JSDOM(html).window.document;
const raw = parseCoreProgram(doc);

// Strip DOM-only fields, keep everything analyze() needs
const categories = raw.map(cat => {
  const base = {
    type: cat.type,
    section: cat.section,
    name: cat.name,
    instructions: cat.instructions,
    coreIndex: cat.coreIndex,
    slug: cat.slug,
  };

  if (cat.type === 'section-header') return base;

  return {
    ...base,
    reqType: cat.reqType,
    minHours: cat.minHours,
    maxHours: cat.maxHours,
    maxPerDiscipline: cat.maxPerDiscipline,
    courses: (cat.courses || []).map(c => ({
      code: c.code,
      title: c.title,
      subDiscipline: c.subDiscipline,
    })),
  };
});

const output = {
  _meta: {
    catoid: CATOID,
    catalogYear: CATALOG_YEARS[CATOID] || null,
    generatedFrom: `catalog-${CATOID}.html`,
    generatedAt: new Date().toISOString().slice(0, 10),
    note: 'Auto-generated by test/generate-catalog-json.js. Re-run when catalog changes.',
  },
  categories,
};

writeFileSync(OUTPUT, JSON.stringify(output, null, 2) + '\n', 'utf-8');

// Print summary
const sections = categories.filter(c => c.type === 'section-header');
const cats = categories.filter(c => c.type !== 'section-header');
const totalCourses = cats.reduce((n, c) => n + (c.courses?.length || 0), 0);
console.log(`Wrote ${OUTPUT}`);
console.log(`  ${sections.length} sections, ${cats.length} categories, ${totalCourses} total courses`);
for (const cat of cats) {
  const courses = cat.courses?.length || 0;
  const details = [cat.reqType];
  if (cat.minHours != null) details.push(`${cat.minHours}–${cat.maxHours}h`);
  if (cat.maxPerDiscipline) details.push(`max ${cat.maxPerDiscipline}h/disc`);
  console.log(`  ${cat.name}: ${courses} courses (${details.join(', ')})`);
}

// ---- Union of all known catalogs → src/catalog-courses.js ----

const catalogFiles = readdirSync(FIXTURES)
  .map(f => f.match(/^catalog-categories-(\d+)\.json$/))
  .filter(Boolean)
  .sort((a, b) => Number(b[1]) - Number(a[1]));  // newest first: its sub-discipline wins
const union = {};
const sources = [];
for (const [file, catoid] of catalogFiles) {
  const data = JSON.parse(readFileSync(join(FIXTURES, file), 'utf-8'));
  sources.push(`${catoid} (${data._meta.catalogYear})`);
  for (const cat of data.categories) {
    if (!cat.name || !cat.courses?.length) continue;
    union[cat.name] ??= {};
    for (const c of cat.courses) {
      if (!(c.code in union[cat.name])) union[cat.name][c.code] = c.subDiscipline || null;
    }
  }
}
for (const name of Object.keys(union)) {
  union[name] = Object.fromEntries(Object.entries(union[name]).sort(([a], [b]) => a.localeCompare(b)));
}
writeFileSync(UNION_OUTPUT, `// Auto-generated by test/generate-catalog-json.js. Do not edit.
// Union of core course lists from catalogs ${sources.join(', ')}.
// { [category name]: { [course code]: sub-discipline or null } }
export const KNOWN_COURSE_CATEGORIES = ${JSON.stringify(union, null, 2)};
`, 'utf-8');
console.log(`Wrote ${UNION_OUTPUT} from catalogs ${sources.join(', ')}`);
